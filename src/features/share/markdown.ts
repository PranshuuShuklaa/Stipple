import type { Scan } from '@/lib/types/scan'

/**
 * Share utility functions and Markdown builders.
 * Pure functions with unit tests.
 */

export function getSiteUrl(): string {
  if (typeof window !== 'undefined' && window.location.origin) {
    return process.env.NEXT_PUBLIC_SITE_URL || window.location.origin
  }
  return process.env.NEXT_PUBLIC_SITE_URL || 'https://stipple.dev'
}

export function getReportUrl(owner: string, repo: string, siteUrl: string = getSiteUrl()): string {
  return `${siteUrl}/r/${owner}/${repo}`
}

export function getBadgeApiUrl(owner: string, repo: string, siteUrl: string = getSiteUrl()): string {
  return `${siteUrl}/api/badge/${owner}/${repo}.svg`
}

export function getCardApiUrl(owner: string, repo: string, siteUrl: string = getSiteUrl()): string {
  return `${siteUrl}/api/card/${owner}/${repo}.svg`
}

export function buildBadgeMarkdown(owner: string, repo: string, siteUrl?: string): string {
  const resolvedUrl = siteUrl || getSiteUrl()
  const badgeUrl = getBadgeApiUrl(owner, repo, resolvedUrl)
  const reportUrl = getReportUrl(owner, repo, resolvedUrl)
  return `[![Stipple health](${badgeUrl})](${reportUrl})`
}

export function buildCardMarkdown(owner: string, repo: string, siteUrl?: string): string {
  const resolvedUrl = siteUrl || getSiteUrl()
  const cardUrl = getCardApiUrl(owner, repo, resolvedUrl)
  const reportUrl = getReportUrl(owner, repo, resolvedUrl)
  return `[![Stipple repo card](${cardUrl})](${reportUrl})`
}

export function buildSummaryMarkdown(scan: Scan, siteUrl?: string): string {
  const resolvedUrl = siteUrl || getSiteUrl()
  const reportUrl = getReportUrl(scan.owner, scan.name, resolvedUrl)
  const topLangs = scan.languages.slice(0, 3).map((l) => l.name).join(', ') || 'Various'
  const contributorCount = scan.contributors.length
  return `### Stipple Summary for [${scan.owner}/${scan.name}](${scan.htmlUrl})
- **Languages**: ${topLangs}
- **Health**: ${scan.health.score} / 100
- **Commits**: ${scan.commits}
- **Contributors**: ${contributorCount}

*[Generated by Stipple](${reportUrl})*`
}

export async function copyToClipboard(text: string): Promise<boolean> {
  if (typeof navigator !== 'undefined' && navigator.clipboard && typeof navigator.clipboard.writeText === 'function') {
    try {
      await navigator.clipboard.writeText(text)
      return true
    } catch {
      // Fallback
    }
  }
  if (typeof document === 'undefined') return false
  const previousFocus =
    document.activeElement instanceof HTMLElement ? document.activeElement : null
  try {
    const textarea = document.createElement('textarea')
    textarea.value = text
    textarea.setAttribute('readonly', '')
    textarea.setAttribute('aria-hidden', 'true')
    textarea.tabIndex = -1
    textarea.style.position = 'fixed'
    textarea.style.opacity = '0'
    document.body.appendChild(textarea)
    textarea.focus()
    textarea.select()
    const successful = document.execCommand('copy')
    document.body.removeChild(textarea)
    previousFocus?.focus()
    return successful
  } catch {
    previousFocus?.focus()
    return false
  }
}
