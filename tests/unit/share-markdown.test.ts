import { describe, expect, it } from 'vitest'
import {
  getReportUrl,
  getBadgeApiUrl,
  getCardApiUrl,
  buildBadgeMarkdown,
  buildCardMarkdown,
  buildSummaryMarkdown,
  pulseSummaryLine,
  structureSummaryLine,
} from '@/features/share/markdown'
import type { Scan } from '@/lib/types/scan'

const mockScan: Scan = {
  owner: 'octocat',
  name: 'Hello-World',
  description: 'My first repo',
  defaultBranch: 'main',
  stars: 120,
  htmlUrl: 'https://github.com/octocat/Hello-World',
  files: [],
  languages: [
    { name: 'TypeScript', bytes: 5000 },
    { name: 'JavaScript', bytes: 2000 },
  ],
  activity: [],
  contributors: [{ login: 'octocat', commits: 10 }],
  commits: 42,
  health: { score: 95, checks: [] },
  dependencies: [],
  flags: { truncated: false, statsPending: false },
  scannedAt: '2026-01-01T00:00:00Z',
}

describe('share markdown builders', () => {
  const siteUrl = 'https://stipple.dev'

  it('generates correct report URL', () => {
    expect(getReportUrl('octocat', 'Hello-World', siteUrl)).toBe('https://stipple.dev/r/octocat/Hello-World')
  })

  it('generates correct badge API URL', () => {
    expect(getBadgeApiUrl('octocat', 'Hello-World', siteUrl)).toBe('https://stipple.dev/api/badge/octocat/Hello-World.svg')
  })

  it('generates correct card API URL', () => {
    expect(getCardApiUrl('octocat', 'Hello-World', siteUrl)).toBe('https://stipple.dev/api/card/octocat/Hello-World.svg')
  })

  it('builds badge markdown correctly', () => {
    const md = buildBadgeMarkdown('octocat', 'Hello-World', siteUrl)
    expect(md).toBe(
      '[![Stipple health](https://stipple.dev/api/badge/octocat/Hello-World.svg)](https://stipple.dev/r/octocat/Hello-World)'
    )
  })

  it('builds card markdown correctly', () => {
    const md = buildCardMarkdown('octocat', 'Hello-World', siteUrl)
    expect(md).toBe(
      '[![Stipple repo card](https://stipple.dev/api/card/octocat/Hello-World.svg)](https://stipple.dev/r/octocat/Hello-World)'
    )
  })

  it('builds summary markdown correctly', () => {
    const md = buildSummaryMarkdown(mockScan, siteUrl)
    expect(md).toContain('### Stipple Summary for [octocat/Hello-World](https://github.com/octocat/Hello-World)')
    expect(md).toContain('- **Languages**: TypeScript, JavaScript')
    expect(md).toContain('- **Health**: 95 / 100')
    expect(md).toContain('- **Commits**: 42')
    expect(md).toContain('- **Contributors**: 1')
    expect(md).toContain('*[Generated by Stipple](https://stipple.dev/r/octocat/Hello-World)*')
  })

  it('pulse summary line uses real pulse values', () => {
    const withPulse: Scan = { ...mockScan, pulse: { days: [], lastCommit: '2026-11-01', activeWeeks: 31, longestStreakWeeks: 9, busiestWeekday: 4, totalCommits: 120, topWeeksShare: 0.3, status: 'active', pattern: 'steady' } }
    expect(pulseSummaryLine(withPulse)).toContain('Pulse: Active')
    expect(pulseSummaryLine(withPulse)).toContain('commits in 31 of 52 weeks')
  })

  it('pulse summary line skips when pulse is null', () => {
    expect(pulseSummaryLine(mockScan)).toBeNull()
  })

  it('structure summary line uses real code split and depth', () => {
    const withStruct: Scan = { ...mockScan, structure: { codeSplit: { source: 62, tests: 18, docs: 5, config: 10, assets: 3, other: 2 }, largest: [], maxDepth: 7, topFolders: 5 } }
    expect(structureSummaryLine(withStruct)).toBe('Structure: 62% source, 18% tests, deepest folder 7 levels')
  })

  it('structure summary line skips when structure is missing', () => {
    expect(structureSummaryLine(mockScan)).toBeNull()
  })
})
